export type RoleModelAbility = {
  name: string;
  weight: number;             // 评估权重（%）
  questionExamples: string[]; // 问题示例
};

export type RoleModel = {
  value: string;
  label: string;
  /** 岗位核心能力（带权重） */
  abilities: RoleModelAbility[];
  /** 专属评分模型（用于最终报告评价，权重总和=100%） */
  scoringModel: RoleModelAbility[];
  /** 必须优先获取的信息 */
  keyInfoToCollect: string[];
  /** 最终报告的评价重心 */
  evaluationFocus: string[];
  /** 当用户无相关经历时的追问方向 */
  fallbackDirection: string;
  /** 真实招聘流程（面试官可据此考察候选人是否了解岗位） */
  hiringProcess: string[];
  /** 常见硬性条件（公开招聘公告惯例，各航司不同） */
  hardRequirements: string[];
  /** 该岗位真实面试里的标志性问题 */
  signatureQuestions: string[];
  /** 真实面试中的扣分红线（报告与提问都要避免/指出） */
  redFlags: string[];
  /** 高分回答的共同特征（用于报告评价） */
  highScoreSignals: string[];
  /** 资料来源（官方招聘页面/招聘简章的公开信息，仅用于还原真实流程与硬性条件） */
  sources?: string[];
};

